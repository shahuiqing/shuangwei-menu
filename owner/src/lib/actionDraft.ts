/* ============ 执行草稿（规则模板，先于 AI） ============
 * 把一个问题转成可执行的步骤清单，供老板直接下发。
 */

export function actionDraft(kind: string): string[] {
  switch (kind) {
    case "price":
      return [
        "核对该原料最新采购价与历史中位价",
        "联系供应商议价，或比价换供应商",
        "更新采购单后观察下周食材成本",
      ];
    case "late":
      return [
        "立即接单并推进出餐",
        "梳理后厨出餐流程，找出超时环节",
        "观察超时订单数量是否下降",
      ];
    case "low":
      return [
        "到采购页按采购计划一键补货",
        "复核安全库存设置是否合理",
        "补货后观察预警是否解除",
      ];
    case "waste":
      return [
        "到损耗分析查看原因分布",
        "定位损耗最大的原料与环节",
        "制定改进措施并记录效果",
      ];
    case "stocktake":
      return ["安排 A 类食材优先盘点", "录入实盘数量", "确认差异并归因到环节"];
    default:
      return ["确认问题属实", "分析根本原因", "制定措施并执行", "观察是否解决"];
  }
}
